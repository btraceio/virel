#!/usr/bin/env python3
"""Generate the benchmark's fixed native metadata (XML-v2 envelope) as C++ includes.

`generation_metadata.inc` is the original hand-built schema; this generator
reproduces it byte for byte (checked) and adds the profiling-sample schema in
`sample_metadata.inc`: a sample event referencing a pooled stack trace, whose
frames reference a pooled method.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
NAMES = ['root', 'metadata', 'region', 'class', 'field', 'name', 'id', 'superType', 'constantPool']
EVENT = 'jdk.jfr.Event'

BASE = [
    ('class', {'name': 'long', 'id': '100'}, []),
    ('class', {'name': 'virel.String', 'id': '101'}, []),
    ('class', {'name': 'virel.bench.event', 'id': '1073741824', 'superType': EVENT}, [
        ('field', {'name': 'startTime', 'class': '100'}, []),
        ('field', {'name': 'sequence', 'class': '100'}, []),
        ('field', {'name': 'producer', 'class': '100'}, []),
        ('field', {'name': 'label', 'class': '101', 'constantPool': '0'}, []),
    ]),
    ('class', {'name': 'virel.eos', 'id': '8', 'superType': EVENT}, []),
]
SAMPLE = BASE[:3] + [
    # Pooled method: name is an inline string so methods depend on no other pool.
    ('class', {'name': 'virel.bench.Method', 'id': '102'}, [
        ('field', {'name': 'name', 'class': '101'}, []),
    ]),
    ('class', {'name': 'virel.bench.StackTrace', 'id': '103'}, [
        ('field', {'name': 'frames', 'class': '104', 'dimension': '1'}, []),
    ]),
    ('class', {'name': 'virel.bench.Frame', 'id': '104'}, [
        ('field', {'name': 'method', 'class': '102', 'constantPool': '0'}, []),
        ('field', {'name': 'bci', 'class': '100'}, []),
    ]),
    ('class', {'name': 'virel.bench.sample', 'id': '1073741825', 'superType': EVENT}, [
        ('field', {'name': 'startTime', 'class': '100'}, []),
        ('field', {'name': 'sequence', 'class': '100'}, []),
        ('field', {'name': 'producer', 'class': '100'}, []),
        ('field', {'name': 'stackTrace', 'class': '103', 'constantPool': '0'}, []),
    ]),
    BASE[3],
]


def varint(v):
    out = bytearray()
    while v >= 128:
        out.append(v & 127 | 128); v >>= 7
    out.append(v)
    return bytes(out)


def encode(classes):
    names = list(NAMES)
    for _, attrs, fields in classes:
        for key in list(attrs) + [k for _, a, _ in fields for k in a]:
            if key not in names:
                names.append(key)
    tree = ('root', {}, [('metadata', {}, classes), ('region', {}, [])])
    # String order of the original blob: supertype, class names, field names,
    # then numeric attribute values sorted as strings.
    words = [EVENT] + [a['name'] for _, a, _ in classes] + [a['name'] for _, _, f in classes for _, a, _ in f]
    numbers = {v for _, a, f in classes for attrs in [a] + [x for _, x, _ in f]
               for k, v in attrs.items() if k != 'name' and v != EVENT}
    values = []
    for v in words + sorted(numbers):
        if v not in names + values:
            values.append(v)
    pool = names + values
    def element(node):
        name, attrs, children = node
        out = varint(pool.index(name)) + varint(len(attrs))
        for k, v in attrs.items():
            out += varint(pool.index(k)) + varint(pool.index(v))
        out += varint(len(children))
        for child in children:
            out += element(child)
        return out
    body = bytes([0, 0, 0, 1, 0]) + varint(len(pool))  # type 0, start, duration, metadata id 1, xml-v2
    for s in pool:
        b = s.encode()
        body += b'\x03' + varint(len(b)) + b
    body += element(tree)
    for width in (1, 2, 3):
        if len(varint(width + len(body))) == width:
            return varint(width + len(body)) + body
    raise ValueError('metadata too large')


def render(name, comment, data):
    rows = [', '.join(str(b) for b in data[i:i+20]) + ',' for i in range(0, len(data), 20)]
    return f'// {comment}\nstatic constexpr uint8_t {name}[] = {{\n' + ''.join(f'    {r}\n' for r in rows) + '};\n'


def main():
    base = render('NATIVE_METADATA', 'Fixed complete metadata for the native benchmark schema (XML-v2 envelope).', encode(BASE))
    if base != (ROOT / 'generation_metadata.inc').read_text():
        raise SystemExit('generator does not reproduce generation_metadata.inc')
    (ROOT / 'sample_metadata.inc').write_text(render(
        'SAMPLE_METADATA', 'Generated by gen_metadata.py: native schema plus pooled stack-trace samples.',
        encode(SAMPLE)))
    print('generation_metadata.inc reproduced; sample_metadata.inc written')


if __name__ == '__main__':
    main()
